// Encodes the per-game UI icons (assets/games/<id>.png) into a TS module of
// base64 data URIs. Data URIs are used rather than Vite asset imports so the
// icons load identically in dev and in the packaged Electron app, with no
// file:// path or asset-emit concerns. Re-run after changing an icon:
//
//   node scripts/build-game-icons.mjs
//
// Source PNGs are 64x64 transparent squares (see the file's git history for how
// they were produced from the upstream RimWorld / Minecraft logos).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const GAMES = ['rimworld', 'minecraft'];

const entries = GAMES.map((id) => {
  const png = readFileSync(path.join(root, 'assets', 'games', `${id}.png`));
  return `  ${id}: 'data:image/png;base64,${png.toString('base64')}',`;
}).join('\n');

const out = `// GENERATED by scripts/build-game-icons.mjs — do not edit by hand.
// Per-game UI icons as base64 data URIs (source: assets/games/<id>.png).
import type { GameId } from '../agent/games/types';

export const GAME_ICONS: Record<GameId, string> = {
${entries}
};
`;

const dest = path.join(root, 'src', 'components', 'game-icons.generated.ts');
writeFileSync(dest, out, 'utf8');
console.log(`Wrote ${path.relative(root, dest)} (${GAMES.join(', ')})`);
